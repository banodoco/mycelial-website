#!/usr/bin/env node
// Preserve native ESM and import.meta URLs in an immutable, retained release tree.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'espree';

const ENTRIES = ['main.js', 'organism/hero-spores.js', 'organism/hero-spores-worker.js', 'hero-deco.js'];
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

/* THE ?rt= OVERRIDE (bisecting on the live site). `releases` is the retained
   snapshot list from runtime-history.json, oldest first. With no `rt`
   parameter the script does exactly what it always did: base is the live
   release. `?rt=<8-64 lowercase hex>` names a retained snapshot by unique
   prefix; anything else (bad characters, unknown, ambiguous) keeps the live
   base and says so in the badge. Only `./runtime/<listed hash>/` can ever be
   chosen. Nothing is persisted: the parameter must be in the URL each time.
   index.html and the root CSS/JS stay the current ones; only the snapshot's
   module graph (main.js, three, the spores worker, hero-deco.js) changes. */
const OVERRIDE = String.raw`
  const rt = /[?&]rt=([^&#]*)/.exec((window.location && window.location.search) || '');
  if (rt) {
    const want = rt[1];
    const hits = /^[0-9a-f]{8,64}$/.test(want) ? releases.filter(r => r[0].startsWith(want)) : [];
    const pick = hits.length === 1 ? hits[0] : null;
    if (pick) active = './runtime/' + pick[0] + '/';
    const index = pick ? releases.indexOf(pick) : -1;
    const liveIndex = releases.findIndex(r => base === './runtime/' + r[0] + '/');
    window.__runtimeOverride = {
      requested: want, hash: pick ? pick[0] : null, live: active === base,
      problem: pick ? null : (hits.length > 1 ? 'ambiguous' : 'unknown'),
      date: pick ? pick[1] : null, label: pick ? pick[3] : null,
    };
    const short = h => {
      for (let n = 8; n < 64; n++) if (releases.filter(r => r[0].startsWith(h.slice(0, n))).length === 1) return h.slice(0, n);
      return h;
    };
    const step = dir => {
      // Releases only; from an unreleased snapshot, the nearest release that way.
      const from = index === -1 ? liveIndex : index;
      for (let i = from + dir; i >= 0 && i < releases.length; i += dir) if (releases[i][2]) return releases[i];
      return null;
    };
    const href = hash => {
      const url = new URL(window.location.href);
      if (hash) url.searchParams.set('rt', short(hash)); else url.searchParams.delete('rt');
      return url.pathname + url.search + url.hash;
    };
    const when = iso => {
      const d = iso ? new Date(iso) : null;
      if (!d || isNaN(d)) return 'date unknown';
      const pad = n => String(n).padStart(2, '0');
      const month = 'Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec'.split(' ')[d.getUTCMonth()];
      return d.getUTCDate() + ' ' + month + ' ' + pad(d.getUTCHours()) + ':' + pad(d.getUTCMinutes()) + ' UTC';
    };
    const showBadge = () => {
      const badge = document.createElement('div');
      badge.id = 'runtime-override-badge';
      badge.setAttribute('role', 'status');
      badge.style.cssText = 'all:initial;position:fixed;left:8px;bottom:8px;z-index:2147483647;max-width:calc(100vw - 16px);box-sizing:border-box;'
        + 'background:#b00020;color:#fff;font:600 12px/1.4 ui-monospace,Menlo,Consolas,monospace;padding:6px 9px;border-radius:4px;'
        + 'box-shadow:0 1px 6px rgba(0,0,0,.5);white-space:normal';
      const text = document.createElement('span');
      text.textContent = pick
        ? 'build ' + pick[0].slice(0, 8) + ' · ' + when(pick[1]) + (pick[3] ? ' · ' + pick[3] : '')
          + (active === base ? ' · this IS the live build' : ' · not the live build')
        : 'rt=' + want.slice(0, 64) + ' is ' + (hits.length > 1 ? 'ambiguous' : 'not a retained build') + ' · showing the LIVE build';
      badge.appendChild(text);
      const link = (label, hash) => {
        const a = document.createElement('a');
        a.textContent = label;
        a.href = href(hash);
        a.style.cssText = 'all:initial;color:#fff;font:inherit;text-decoration:underline;margin-left:10px;cursor:pointer';
        badge.appendChild(a);
      };
      const older = step(-1), newer = step(1);
      if (older) link('‹ older', older[0]);
      if (newer) link('newer ›', newer[0]);
      link('live', null);
      document.body.appendChild(badge);
    };
    if (document.body) showBadge();
    else document.addEventListener('DOMContentLoaded', showBadge, { once: true });
  }
`;

export function runtimeBootstrap(base, releases = []) {
  const list = releases.map(r => `    ${JSON.stringify([r.hash, r.date || '', r.release ? 1 : 0, r.label || ''])},\n`).join('');
  return `// Generated by tools/build-runtime-release.mjs; retain every runtime release.\n` +
    `(() => {\n` +
    `  const base = ${JSON.stringify(base)};\n` +
    `  // Retained snapshots, oldest first: [sha256, build time (UTC), 1 = was the live release, label].\n` +
    `  const releases = [\n${list}  ];\n` +
    `  let active = base;\n` +
    OVERRIDE.slice(1) +
    `  window.__runtimeBase = active;\n` +
    `  const map = document.createElement('script');\n` +
    `  map.type = 'importmap';\n` +
    `  map.textContent = JSON.stringify({ imports: {\n` +
    `    './main.js': active + 'main.js',\n` +
    `    './organism/hero-spores.js': active + 'organism/hero-spores.js',\n` +
    `    'three': active + 'vendor/three/three.module.js',\n` +
    `    'three/addons/': active + 'vendor/three/addons/',\n` +
    `  } });\n` +
    `  document.head.appendChild(map);\n` +
    `})();\n`;
}

const HISTORY = 'runtime-history.json';
const HASH = /^[a-f0-9]{64}$/;

/** The retained-snapshot history, validated against runtime/. In build mode
 *  missing snapshots are added (the current one with this build's time);
 *  in check mode any drift is an error. */
export function runtimeHistory(root, current, { check = false, now = new Date() } = {}) {
  const path = resolve(root, HISTORY);
  const history = existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : { version: 1, releases: [] };
  if (history.version !== 1 || !Array.isArray(history.releases)) throw new Error(`Invalid ${HISTORY}`);
  const seen = new Set();
  for (const entry of history.releases) {
    if (!entry || !HASH.test(entry.hash) || seen.has(entry.hash) || typeof entry.date !== 'string'
      || (entry.date && Number.isNaN(Date.parse(entry.date))) || typeof entry.label !== 'string') {
      throw new Error(`Invalid ${HISTORY} entry: ${JSON.stringify(entry)}`);
    }
    seen.add(entry.hash);
  }
  const directory = resolve(root, 'runtime');
  const retained = existsSync(directory) ? readdirSync(directory).filter(name => HASH.test(name)).sort() : [];
  const missing = retained.filter(hash => !seen.has(hash) && hash !== current);
  const extra = [...seen].filter(hash => !retained.includes(hash) && hash !== current);
  if (extra.length) throw new Error(`${HISTORY} lists snapshots that are not retained: ${extra.join(', ')}`);
  if (check) {
    if (missing.length || !seen.has(current)) throw new Error(`Runtime release is stale; ${HISTORY} does not list every retained snapshot; run npm run runtime:build`);
    return history;
  }
  for (const hash of missing) history.releases.push({ hash, date: '', release: false, label: '' });
  if (!seen.has(current)) history.releases.push({ hash: current, date: now.toISOString().replace(/\.\d+Z$/, 'Z'), release: true, label: '' });
  return history;
}

function historyText(history) {
  const { releases, ...head } = history;
  const fields = Object.entries(head).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},\n`).join('');
  return `{\n${fields}  "releases": [\n${releases.map(r => `    {${Object.entries(r).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(', ')}}`).join(',\n')}\n  ]\n}\n`;
}

function walkAst(node, visit) {
  if (!node || typeof node !== 'object') return;
  visit(node);
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach(item => walkAst(item, visit));
    else if (value && typeof value === 'object') walkAst(value, visit);
  }
}

export function collectRuntime(root) {
  const files = new Map();
  function add(path) {
    const full = resolve(root, path);
    const key = relative(root, full).split(sep).join('/');
    if (key.startsWith('../') || key === '..') throw new Error(`Runtime path escapes source: ${path}`);
    if (files.has(key)) return;
    const bytes = readFileSync(full);
    files.set(key, bytes);
    if (!key.endsWith('.js')) return;
    const ast = parse(bytes.toString('utf8'), { ecmaVersion: 'latest', sourceType: 'module' });
    walkAst(ast, node => {
      let specifier;
      if (['ImportDeclaration', 'ExportNamedDeclaration', 'ExportAllDeclaration'].includes(node.type)) {
        specifier = node.source?.value;
      } else if (node.type === 'ImportExpression') {
        if (node.source.type !== 'Literal') throw new Error(`Nonliteral runtime import in ${key}`);
        specifier = node.source.value;
      }
      if (typeof specifier !== 'string') return;
      if (specifier === 'three') add('vendor/three/three.module.js');
      else if (specifier.startsWith('three/addons/')) add(`vendor/three/addons/${specifier.slice(13)}`);
      else if (specifier.startsWith('.')) {
        if (/[?#]/.test(specifier)) throw new Error(`Versioned source specifier in ${key}: ${specifier}`);
        add(relative(root, resolve(dirname(full), specifier)));
      } else throw new Error(`Unmapped runtime import in ${key}: ${specifier}`);
    });
  }
  ENTRIES.forEach(add);
  // These resources use import.meta-relative URLs, not ESM imports.
  add('assets/contributor-portraits/profile-sprite.jpg');
  add('static/geom/manifest.json');
  const manifest = JSON.parse(files.get('static/geom/manifest.json'));
  for (const chapter of Object.values(manifest.chapters)) add(`static/geom/${chapter.file}`);
  return new Map([...files].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
}

function releaseHash(files) {
  const hash = createHash('sha256');
  for (const [path, bytes] of files) hash.update(path).update('\0').update(sha256(bytes)).update('\n');
  return hash.digest('hex');
}

export function verifyRetainedReleases(root) {
  const directory = resolve(root, 'runtime');
  if (!existsSync(directory)) throw new Error('No runtime release; run npm run runtime:build');
  for (const name of readdirSync(directory)) {
    if (!/^[a-f0-9]{64}$/.test(name)) throw new Error(`Unexpected runtime release path: ${name}`);
    const manifest = JSON.parse(readFileSync(resolve(directory, name, 'manifest.json'), 'utf8'));
    if (manifest.version !== 1 || manifest.hash !== name) throw new Error(`Invalid runtime manifest: ${name}`);
    const files = new Map();
    for (const entry of manifest.files) {
      if (entry.path.startsWith('/') || entry.path.split('/').includes('..')) throw new Error('Unsafe runtime manifest path');
      const bytes = readFileSync(resolve(directory, name, entry.path));
      if (sha256(bytes) !== entry.sha256) throw new Error(`Modified immutable runtime: ${name}/${entry.path}`);
      files.set(entry.path, bytes);
    }
    if (releaseHash(files) !== name) throw new Error(`Runtime release hash mismatch: ${name}`);
  }
}

export function buildRuntimeRelease({ root, check = false }) {
  const files = collectRuntime(root);
  const hash = releaseHash(files);
  const base = `./runtime/${hash}/`;
  const destination = resolve(root, 'runtime', hash);
  if (check) {
    verifyRetainedReleases(root);
    const bootstrap = runtimeBootstrap(base, runtimeHistory(root, hash, { check: true }).releases);
    if (!existsSync(destination) || readFileSync(resolve(root, 'runtime-release.js'), 'utf8') !== bootstrap) {
      throw new Error('Runtime release is stale; run npm run runtime:build and stage its output');
    }
  } else {
    if (existsSync(resolve(root, 'runtime'))) verifyRetainedReleases(root);
    if (!existsSync(destination)) {
      mkdirSync(resolve(root, 'runtime'), { recursive: true });
      const temporary = resolve(root, 'runtime', `.pending-${process.pid}`);
      try {
        mkdirSync(temporary);
        for (const [path, bytes] of files) {
          const target = resolve(temporary, path);
          mkdirSync(dirname(target), { recursive: true });
          writeFileSync(target, bytes);
        }
        writeFileSync(resolve(temporary, 'manifest.json'), JSON.stringify({
          version: 1, hash, entries: ENTRIES,
          files: [...files].map(([path, bytes]) => ({ path, sha256: sha256(bytes) })),
        }, null, 2) + '\n');
        renameSync(temporary, destination);
      } finally { rmSync(temporary, { recursive: true, force: true }); }
    }
    const history = runtimeHistory(root, hash);
    const historyTemporary = resolve(root, `.runtime-history-${process.pid}.tmp`);
    writeFileSync(historyTemporary, historyText(history));
    renameSync(historyTemporary, resolve(root, HISTORY));
    const temporary = resolve(root, `.runtime-release-${process.pid}.tmp`);
    writeFileSync(temporary, runtimeBootstrap(base, history.releases));
    renameSync(temporary, resolve(root, 'runtime-release.js'));
  }
  return { hash, base, files: files.size, bytes: [...files.values()].reduce((sum, bytes) => sum + bytes.length, 0) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const rootIndex = args.indexOf('--root');
  if (rootIndex !== -1 && (!args[rootIndex + 1] || args[rootIndex + 1].startsWith('--'))) {
    throw new Error('--root requires a directory');
  }
  const root = rootIndex === -1 ? resolve(dirname(fileURLToPath(import.meta.url)), '..') : resolve(args[rootIndex + 1]);
  if (args.some((arg, index) => arg !== '--check' && arg !== '--root' && !(rootIndex !== -1 && index === rootIndex + 1))) {
    throw new Error('Usage: node tools/build-runtime-release.mjs [--check] [--root PATH]');
  }
  console.log(`runtime release ${args.includes('--check') ? 'verified' : 'built'}: ${JSON.stringify(buildRuntimeRelease({ root, check: args.includes('--check') }))}`);
}
