const { chromium } = require('playwright');
const port = process.argv[2] || '8155', tag = process.argv[3] || 'x', shots = process.argv[4] === 'shots';
const OUT = '/tmp/claude-0/-home-user/62a00d20-ec8d-551d-aa8b-33233b07a42e/scratchpad/captures/IMPL-hoverfix';
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1024, height: 640 }, deviceScaleFactor: shots ? 2 : 1, reducedMotion: process.env.RM || 'reduce' });
  page.on('pageerror', e => console.log('[pageerror]', e.message));
  await page.goto(`http://localhost:${port}/?nointro=1`);
  await page.waitForFunction(() => window.journey, null, { timeout: 600000 });
  await page.evaluate(() => window.journey.flyTo('manifesto'));
  await page.waitForSelector('.j-manifesto.is-open', { timeout: 600000 });
  await page.waitForFunction(() => document.querySelectorAll('.j-manifesto-line.shown').length === 5, null, { timeout: 600000 });
  await page.waitForTimeout(8000);
  const read = () => page.evaluate(() => {
    const t = document.querySelector('.manifesto-phrase-thread'), s = getComputedStyle(t);
    const a = (s.backgroundImage.match(/rgba?\([^)]*\)/g) || []).map(c => c.split(/[ ,\/]+/).pop().replace(')', ''));
    return { hover: s.getPropertyValue('--thread-hover'), str: s.getPropertyValue('--thread-strength'), matches: t.matches(':hover'), tr: s.transitionProperty, alphas: a, anim: s.animationName, pe: s.pointerEvents };
  });
  console.log('raf frames in 2s', await page.evaluate(()=>new Promise(r=>{let n=0;const f=()=>{n++;requestAnimationFrame(f)};f();setTimeout(()=>r(n),2000)})));
  if(process.env.NOTR) await page.addStyleTag({content:'.manifesto-phrase-thread,.manifesto-phrase-thread:hover{transition:none!important}'});
  await page.mouse.move(2, 2);
  console.log('rest', JSON.stringify(await read()));
  const t = page.locator('.manifesto-phrase-thread');
  const box = await t.boundingBox();
  const clip = { x: Math.max(0, box.x - 20), y: Math.max(0, box.y - 20), width: Math.min(box.width + 40, 900 - box.x + 20), height: box.height + 40 };
  if (shots) await page.screenshot({ path: `${OUT}/rest-${tag}.png`, clip, timeout: 150000 });
  const words = await t.locator('.j-manifesto-word').all();
  const at = async (name, x, y) => { await page.mouse.move(x, y, { steps: 3 }); await page.waitForTimeout(500); console.log(name, JSON.stringify(await read())); };
  const b0 = await words[0].boundingBox();
  await at('first', b0.x + b0.width / 2, b0.y + b0.height / 2);
  if (shots) await page.screenshot({ path: `${OUT}/hover-${tag}.png`, clip, timeout: 150000 });
  const b1 = await words[1].boundingBox();
  await at('gap', b0.x + b0.width + (b1.x - b0.x - b0.width) / 2, b0.y + b0.height / 2);
  const bl = await words.at(-1).boundingBox();
  await at('last', bl.x + bl.width / 2, bl.y + bl.height / 2);
  await page.mouse.move(2, 2); await page.waitForTimeout(300);
  console.log('after300', JSON.stringify(await read()));
  await page.waitForTimeout(600);
  console.log('after900', JSON.stringify(await read()));
  await browser.close();
})();
